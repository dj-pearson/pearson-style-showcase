#!/usr/bin/env node
/**
 * Generates src/content/crm-articles.generated.ts from the markdown in
 * content/crm.
 *
 * Why: the article page fetches bodies from Supabase by slug, but the pages
 * themselves are prerendered from markdown at build time. Those are two
 * independent sources, and when the seed migrations have not been applied the
 * result is a URL that serves a complete article to a crawler and "Article Not
 * Found" to a human the moment React mounts (US-074, which is the live state of
 * production today). This module is the fallback: when the database has no row
 * for a prerendered slug, or cannot be reached at all, the app renders the same
 * markdown the page was built from.
 *
 *   node scripts/generate-article-fallback.mjs
 *
 * The output is committed so dev and test runs need no build step. Its
 * freshness is asserted in scripts/__tests__/article-fallback.test.ts, which
 * regenerates and compares - a stale file fails the suite rather than silently
 * serving old copy. It is imported dynamically, so none of it reaches the
 * initial bundle.
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readArticles } from './lib/content.mjs';

const OUT = join('src', 'content', 'crm-articles.generated.ts');
const INDEX_OUT = join('src', 'content', 'crm-article-index.generated.ts');

function toEntries(articles) {
  const entries = articles
    .filter(({ meta }) => meta.published)
    .map(({ meta, body }) => ({
      slug: meta.slug,
      title: meta.title,
      excerpt: meta.excerpt,
      content: body,
      category: meta.category,
      tags: meta.tags,
      author: meta.author,
      read_time: meta.read_time,
      featured: meta.featured,
      seo_title: meta.seo_title,
      seo_description: meta.seo_description,
      seo_keywords: meta.seo_keywords,
      published_at: meta.published_at,
      updated_at: meta.updated_at || meta.published_at,
    }))
    .sort((a, b) => a.slug.localeCompare(b.slug));

  return entries;
}

export function renderModule(articles) {
  const entries = toEntries(articles);

  return `// Generated by scripts/generate-article-fallback.mjs. Do not edit.
//
// Edit the markdown in content/crm and regenerate. Freshness is asserted by
// scripts/__tests__/article-fallback.test.ts.

export interface StaticArticle {
  slug: string;
  title: string;
  excerpt: string;
  content: string;
  category: string;
  tags: string[];
  author: string;
  read_time: string;
  featured: boolean;
  seo_title: string;
  seo_description: string;
  seo_keywords: string[];
  published_at: string;
  updated_at: string;
}

export const CRM_ARTICLES: StaticArticle[] = ${JSON.stringify(entries, null, 2)};

export function findStaticArticle(slug: string): StaticArticle | undefined {
  return CRM_ARTICLES.find((article) => article.slug === slug);
}
`;
}

/**
 * A second module carrying the same articles without their bodies. Listing
 * pages need titles and tags, not 150KB of markdown, and they import this
 * statically - so the split is what keeps the hub from pulling every article
 * body into its route chunk.
 */
export function renderIndexModule(articles) {
  const entries = toEntries(articles).map(({ content: _content, ...summary }) => summary);

  return `// Generated by scripts/generate-article-fallback.mjs. Do not edit.
//
// Article metadata without the bodies, for listing pages. Edit the markdown in
// content/crm and regenerate.

export interface StaticArticleSummary {
  slug: string;
  title: string;
  excerpt: string;
  category: string;
  tags: string[];
  author: string;
  read_time: string;
  featured: boolean;
  seo_title: string;
  seo_description: string;
  seo_keywords: string[];
  published_at: string;
  updated_at: string;
}

export const CRM_ARTICLE_INDEX: StaticArticleSummary[] = ${JSON.stringify(entries, null, 2)};
`;
}

if (process.argv[1] && process.argv[1].endsWith('generate-article-fallback.mjs')) {
  const articles = readArticles();
  writeFileSync(OUT, renderModule(articles));
  writeFileSync(INDEX_OUT, renderIndexModule(articles));
  console.log(`generate:fallback: wrote ${OUT} and ${INDEX_OUT}`);
}
